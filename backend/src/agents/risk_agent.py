"""RiskAI - リスク管理・悪魔の代弁者エージェント"""
import random
from typing import Dict, List

from .base_agent import BaseAgent


class RiskAgent(BaseAgent):
    def __init__(self):
        super().__init__(
            agent_id="risk",
            name="RiskAI",
            display_name="リスクAI",
            personality_description=(
                "リスク管理専門家・議論の悪魔の代弁者。"
                "すべての投資提案に対して「なぜこれは間違える可能性があるのか」を3つ以上指摘する。"
                "投資仮説が崩れる具体的な条件（数値・イベント）を明文化する。"
                "賛成するのが仕事ではなく、見落とされたリスクを発見するのが唯一の仕事。"
                "最大損失見込みと撤退条件を必ず提示する。口癖：「何が間違えるか考えろ」"
            ),
            style="リスク管理 / 反証 / 撤退条件設定 / 最大損失見積もり",
            favorite_sectors=["なし（全銘柄のリスク評価）"],
            catchphrase="何が間違えるか考えろ",
        )

    def analyze_market(self, market_data: Dict) -> Dict:
        sp500_change = market_data.get("sp500_change_pct", 0)

        if sp500_change > 1:
            summary = (
                "上昇相場で見落とされがちなリスクを列挙する。"
                "① 過熱感：株高が続くほど調整時の下落幅は大きくなる。"
                "② 流動性リスク：市場全体が上昇している局面では、個別株の選別眼が鈍る。"
                "③ ポジションサイズ：好調時に大きく張ると、悪化時の損失が致命的になる。"
                "キャッシュ比率を意識的に維持し、次の押し目に備えるべきだ。"
            )
        elif sp500_change < -1:
            summary = (
                "下落局面でのリスク管理を確認する。"
                "① パニック売りの回避：仮説が崩れていないなら売りは禁物。"
                "② 追加買いの条件：仮説が正しいなら下落は機会だが、証拠なき逆張りは禁忌。"
                "③ 損切りライン：各ポジションについて、どこまで下落したら仮説を諦めるかを再確認せよ。"
            )
        else:
            summary = (
                "横ばい相場のリスク：「何も起きていない」ことへの安心感が最大のリスクだ。"
                "ボラティリティが低い時期に潜在リスクは蓄積される。"
                "全保有ポジションの投資仮説が現在も有効かを再確認し、"
                "有効でないものは感情なく手放す準備をすべきだ。"
            )

        return {
            "agent_id": self.agent_id,
            "summary": summary,
            "sentiment": "cautious",
            "confidence": 0.8,
        }

    def propose_trades(self, opportunities: List) -> List[Dict]:
        return []  # RiskAIは取引提案をしない。反証と撤退条件の提示のみ。

    def respond_to_peer(self, peer_name: str, peer_opinion: str, context: str = "") -> str:
        responses = [
            f"{peer_name}の提案に反証する。"
            "この投資仮説が崩れるシナリオを3つ挙げる。"
            "① 為替の反転。② 決算での業績下振れ。③ 地政学リスクの顕在化。"
            "これらのうち一つでも発生した場合の最大損失を計算した上で、サイズを決めるべきだ。",

            "興味深い提案だが、撤退条件を明文化していない。"
            "「何かあったら売る」では遅い。"
            "具体的に、ドル円が何円を割ったら撤退するか、"
            "業績が何%下振れたら仮説を諦めるかを決めてから入るべきだ。",

            "買いの根拠はわかった。では反対側を考えよう。"
            "この銘柄が-20%になる可能性は何%か。"
            "期待値が正でもボラティリティが高ければポジションサイズを落とすべきだ。"
            "リスクリワードの数値を出してから判断してほしい。",

            "提案に賛成するには、まず以下の質問に答えてほしい。"
            "① この材料は株価に何%織り込まれているか。"
            "② 3ヶ月後にこの仮説が外れていたとしたら、何が起きているか。"
            "③ そのシナリオへの備えはあるか。",
        ]
        return random.choice(responses)
